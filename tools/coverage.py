"""Write docs/coverage.md from the conformance suite: the mock result, the site result and the citation per cell.

The mock column comes from a fresh run of tests/conformance on the mock. The site column comes from
docs/conformance-live.json, which `pytest tests/conformance --live` writes.

    uv run python tools/coverage.py
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIVE = ROOT / "docs" / "conformance-live.json"
OUT = ROOT / "docs" / "coverage.md"
RANK = {"fail": 2, "skip": 1, "pass": 0}


def worst(outcomes):
    """The outcome that matters most for a cell: fail over skip over pass."""
    return max(outcomes, key=lambda o: RANK[o])


def evidence(tests):
    """`api3` when every test in the group cites an api3 record, otherwise `REST only`."""
    return "api3" if all(t["api3"] for t in tests) else "REST only"


def site_result(live, nodeids):
    """The worst live outcome over ``nodeids``, or `gap` when the live run has none of them."""
    found = [live["tests"][n]["outcome"] for n in nodeids if live and n in live["tests"]]
    return worst(found) if found else "gap"


def render(mock, live):
    """The coverage page as markdown, from the mock results and the live results or None."""
    if live:
        header = "Site: Flow PT %s. Live run: %s." % (live["site_version"] or "unknown", live["date"])
    else:
        header = "No live run recorded. The site column reads `gap`."
    cells, other = {}, []
    for nodeid, t in sorted(mock["tests"].items()):
        if t["cell"]:
            cells.setdefault(tuple(t["cell"]), []).append((nodeid, t))
        else:
            other.append((nodeid, t))
    lines = [
        "# Coverage",
        "",
        "Generated by `tools/coverage.py` from `tests/conformance/`. Do not edit by hand.",
        "",
        header,
        "",
        "`REST only`: the finding was measured over REST and its api3 probe is open (sg-groundtruth#109).",
        "",
        "| method | operator | field type | mock | site | finding | evidence |",
        "|---|---|---|---|---|---|---|",
    ]
    for cell in sorted(cells):
        group = cells[cell]
        tests = [t for _, t in group]
        findings = ", ".join(sorted(set(t["finding"] for t in tests)))
        lines.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            cell[0], cell[1], cell[2], worst([t["outcome"] for t in tests]),
            site_result(live, [n for n, _ in group]), findings, evidence(tests)))
    if other:
        lines += ["", "Tests outside the table:", "", "| test | mock | site | finding | evidence |", "|---|---|---|---|---|"]
        for nodeid, t in other:
            lines.append("| `%s` | %s | %s | %s | %s |" % (
                nodeid.split("::")[-1], t["outcome"], site_result(live, [nodeid]), t["finding"], evidence([t])))
    return "\n".join(lines) + "\n"


def run_mock():
    """Run tests/conformance on the mock and return its results."""
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "mock.json"
        subprocess.run([sys.executable, "-m", "pytest", "tests/conformance", "-q", "-p", "no:cacheprovider",
                        "--conformance-out", str(out)], cwd=ROOT, check=False)
        return json.loads(out.read_text())


def main():
    live = json.loads(LIVE.read_text()) if LIVE.is_file() else None
    OUT.write_text(render(run_mock(), live))
    print("wrote %s" % OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
